"""Caddyfile for a node.

Caddy gets the certificate and routes by path:
  /<panel_path>/...   -> the panel        (only on the panel's own server)
  /<sub_path>/...     -> subscriptions    (only on the panel's own server)
  /<xhttp path>...    -> Xray XHTTP inbound
  /<ws path>...       -> Xray WebSocket inbound
  /<grpc service>/... -> Xray gRPC inbound
  everything else     -> a plain static site, so the domain looks ordinary.

Normally Caddy owns ports 80 and 443. When Reality takes 443 (Node.reality_front)
Caddy keeps port 80 for redirects and ACME, and serves HTTPS on 127.0.0.1
behind Xray, which forwards it every connection that is not a Reality client,
with a PROXY protocol header so the real client address survives.

Every value interpolated below has already passed model.py validation.
"""

from __future__ import annotations

from typing import Any

from .model import CADDY_BEHIND_PORT, Node, is_ip

SITE_ROOT = "/var/www/xcpanel"
HEADER = "# Generated by xcpanel. Manual edits are overwritten on the next deploy.\n"


def hosts(node: Node, settings: dict[str, Any]) -> list[str]:
    """Domains this node's Caddy serves, in the order the site blocks appear."""
    out = []
    if node.local and settings.get("domain"):
        out.append(settings["domain"])
    if node.caddy and not is_ip(node.address) and node.address not in out:
        out.append(node.address)
    return out


def _proxy(matcher: str, paths: str, upstream: str, streaming: bool = False) -> list[str]:
    lines = [f"\t@{matcher} path {paths}", f"\thandle @{matcher} {{"]
    if streaming:
        lines += [f"\t\treverse_proxy {upstream} {{", "\t\t\tflush_interval -1", "\t\t}"]
    else:
        lines.append(f"\t\treverse_proxy {upstream}")
    lines.append("\t}")
    return lines


def _routes(node: Node, host: str, settings: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    if node.local and host == settings.get("domain"):
        panel = settings["panel_listen"]
        p, s = settings["panel_path"], settings["sub_path"]
        lines += _proxy("panel", f"/{p} /{p}/*", panel)
        lines += _proxy("sub", f"/{s}/*", panel)
    if host == node.address:
        for kind in node.tls_transports():
            t = node.transports[kind]
            if kind == "xhttp":
                upstream = f"h2c://127.0.0.1:{t['port']}"
                lines += _proxy("xhttp", f"{t['path']} {t['path']}/*", upstream, streaming=True)
            elif kind == "ws":
                lines += _proxy("ws", f"{t['path']} {t['path']}/*", f"127.0.0.1:{t['port']}")
            elif kind == "grpc":
                upstream = f"h2c://127.0.0.1:{t['port']}"
                lines += _proxy("grpc", f"/{t['service']}/*", upstream, streaming=True)
    return lines


def build_caddyfile(node: Node, settings: dict[str, Any]) -> str:
    sites = hosts(node, settings)
    front = node.reality_front

    options = []
    if settings.get("acme_email"):
        options.append(f"\temail {settings['acme_email']}")
    if front:
        options += [
            f"\thttps_port {CADDY_BEHIND_PORT}",
            f"\tservers 127.0.0.1:{CADDY_BEHIND_PORT} {{",
            "\t\tlistener_wrappers {",
            "\t\t\tproxy_protocol {",
            "\t\t\t\tallow 127.0.0.1/32",
            "\t\t\t}",
            "\t\t\ttls",
            "\t\t}",
            "\t\tprotocols h1 h2",
            "\t}",
        ]

    out = [HEADER]
    if options:
        out += ["{", *options, "}", ""]
    if front and sites:
        out += [", ".join(f"http://{h}" for h in sites) + " {", "\tredir https://{host}{uri} 308", "}", ""]
    for host in sites:
        out.append(f"{host} {{")
        if front:
            out.append("\tbind 127.0.0.1")
        out += _routes(node, host, settings)
        out += [
            "\thandle {",
            f"\t\troot * {SITE_ROOT}",
            "\t\tencode zstd gzip",
            "\t\tfile_server",
            "\t}",
            "}",
            "",
        ]
    return "\n".join(out)
