def resolve_queries(preset: str | None, queries: list[str] | None) -> list[str]:
    """Собирает итоговый список поисковых запросов из пресета и явных значений."""
    result: list[str] = []
    if preset:
        for name in preset.split(","):
            key = name.strip().lower()
            if key not in PRESETS:
                raise KeyError(key)
            result.extend(PRESETS[key])
    if queries:
        result.extend(q.strip() for q in queries if q.strip())
    # Убираем дубликаты, сохраняя порядок.
    return list(dict.fromkeys(result))
